export const getArticleById = (id) => {
  return articles.find(art => art.id === id) || null;
};

export const getFeaturedArticles = () => {
  return articles.filter(art => art.isFeatured);
};

export const getTrendingArticles = () => {
  return articles
    .filter(art => art.isTrending)
    .sort((a, b) => (a.trendingRank || 99) - (b.trendingRank || 99));
};

export const getArticlesByCategory = (categorySlug) => {
  if (!categorySlug || categorySlug === "all") return articles;
  return articles.filter(art => art.category === categorySlug);
};
